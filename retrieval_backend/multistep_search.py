def action_skill_id(action: str, slot_index: int | None = None) -> str:
    resolved = str(action).strip()
    if resolved not in SLOTTED_ACTIONS:
        if slot_index is not None:
            raise ValueError(f"non-slotted action cannot carry a slot: {resolved}")
        return resolved
    if slot_index is None or not 0 <= int(slot_index) < ACTION_SLOT_COUNT:
        raise ValueError(f"slotted action requires slot 0..{ACTION_SLOT_COUNT - 1}")
    return f"{resolved}@{int(slot_index):03d}"


def parse_action_skill(skill_id: str) -> tuple[str, int | None]:
    raw = str(skill_id).strip()
    head, marker, tail = raw.partition("@")
    if not marker:
        if head in ACTION_ORDER:
            return head, None
        raise ValueError(f"unknown retrieval action skill: {raw}")
    if head not in SLOTTED_ACTIONS or not tail.isdigit():
        raise ValueError(f"invalid retrieval action skill: {raw}")
    slot = int(tail)
    if not 0 <= slot < ACTION_SLOT_COUNT:
        raise ValueError(f"retrieval action slot is out of range: {raw}")
    return head, slot


def _action_skills() -> tuple[dict[str, Any], ...]:
    by_action = {str(row["skill_id"]): row for row in BASE_ACTION_SKILLS}
    output: list[dict[str, Any]] = []
    for action in (SEARCH_PAPERS, RERANK_RESULTS, STOP):
        output.append(dict(by_action[action]))
    for action in SLOTTED_ACTIONS:
        base = by_action[action]
        for slot in range(ACTION_SLOT_COUNT):
            copied = dict(base)
            copied["skill_id"] = action_skill_id(action, slot)
            copied["name"] = f"{base['name']} — slot {slot + 1}"
            copied["description"] = (
                f"{base['description']} Use deterministic current-result slot {slot + 1}."
            )
            copied["body"] = (
                f"{base['body']} The executor binds slot {slot + 1}; no parameter is generated by the model."
            )
            copied["base_action"] = action
            copied["slot_index"] = slot
            output.append(copied)
    return tuple(output)


