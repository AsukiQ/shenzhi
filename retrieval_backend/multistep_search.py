"""Executable multi-step paper retrieval for the Shenzhi KG backend.

Stage2 selects one abstract operation skill at each decision.  This module owns
the deterministic argument binding and execution semantics, so the model never
has to invent author names, keyword IDs, or paper IDs.  The same executor is
used for weak-bootstrap trajectory generation and online HTTP inference.
"""

